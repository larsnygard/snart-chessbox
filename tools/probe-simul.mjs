import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('[err]', m.text().slice(0, 200)); });
await page.goto('http://127.0.0.1:8741/#/simultan', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => !document.getElementById('boot'), null, { timeout: 20000 }).catch(() => {});
await page.waitForTimeout(800);
await page.getByRole('button', { name: /Start simultan/ }).click();
await page.waitForTimeout(1500);
const label = async () => (await page.locator('.board-col strong').first().textContent().catch(() => 'none'));
const buttons = async () => page.locator('.board-col .row button').allTextContents();
console.log('after start:', await label(), JSON.stringify(await buttons()));
await page.getByRole('button', { name: 'Next ▶' }).click();
await page.waitForTimeout(600);
console.log('after next:', await label(), JSON.stringify(await buttons()));
await page.getByRole('button', { name: 'Next ▶' }).click();
await page.waitForTimeout(600);
console.log('after next2:', await label());
await page.getByRole('button', { name: '◀ Previous' }).click();
await page.waitForTimeout(600);
console.log('after prev:', await label());
await page.screenshot({ path: '/home/lars/.hermes/cache/scratch/shots/simultan.png' });
await browser.close();
